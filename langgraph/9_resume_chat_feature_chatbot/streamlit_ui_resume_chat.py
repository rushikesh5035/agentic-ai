import streamlit as st
from chatbot import chatbot
from langchain_core.messages import HumanMessage, AIMessage
import uuid


# ==========================================================
#                    UTILITY FUNCTIONS
# ==========================================================


# Generate a unique thread ID for each conversation.
# LangGraph uses this ID to identify and retrieve chat state.
def generate_thread_id():
    return str(uuid.uuid4())


# Add a new thread to the chat history.
# Each thread contains a unique ID and a user-friendly name.
def add_thread(thread_id):

    # Check whether the thread already exists.
    for thread in st.session_state["chat_threads"]:
        if thread["thread_id"] == thread_id:
            return

    # Generate a sequential name for the new conversation.
    thread_name = f"Thread {len(st.session_state['chat_threads']) + 1}"

    # Store the thread ID and its display name.
    st.session_state["chat_threads"].append(
        {"thread_id": thread_id, "thread_name": thread_name}
    )


# Start a new conversation when the New Chat button is clicked.
def reset_chat():

    # Generate a unique ID for the new conversation.
    thread_id = generate_thread_id()

    # Set the newly created thread as the active conversation.
    st.session_state["thread_id"] = thread_id

    # Add the new conversation to the sidebar history.
    add_thread(thread_id)

    # Clear the previous conversation from the chat interface.
    st.session_state["messages_history"] = []


# Retrieve the conversation history from the LangGraph checkpointer.
def load_conversation(thread_id):

    # Retrieve the latest graph state for the selected thread.
    state = chatbot.get_state(config={"configurable": {"thread_id": thread_id}})

    # Return an empty list if the conversation has no messages.
    return state.values.get("messages", [])


# ==========================================================
#                  SESSION STATE SETUP
# ==========================================================


# Initialize the message history for the active conversation.
if "messages_history" not in st.session_state:
    st.session_state["messages_history"] = []


# Generate an initial thread ID when the application starts.
if "thread_id" not in st.session_state:
    st.session_state["thread_id"] = generate_thread_id()


# Initialize the list that stores all chat conversations.
if "chat_threads" not in st.session_state:
    st.session_state["chat_threads"] = []


# Register the current thread in the conversation history.
# The add_thread function prevents duplicate entries.
add_thread(st.session_state["thread_id"])


# ==========================================================
#                       SIDEBAR
# ==========================================================


st.sidebar.title("LangGraph Chatbot")


# Create a new conversation when the user clicks New Chat.
if st.sidebar.button("＋ New Chat", use_container_width=True):
    reset_chat()


st.sidebar.divider()
st.sidebar.header("My History")


# Reverse the thread list so that the newest conversation
# appears at the top and older conversations appear below.
for thread in reversed(st.session_state["chat_threads"]):
    thread_id = thread["thread_id"]
    thread_name = thread["thread_name"]

    # Check whether this thread is currently active.
    is_active = thread_id == st.session_state["thread_id"]

    # Display the thread name instead of its UUID.
    # Use the UUID as the unique key for each button.
    if st.sidebar.button(
        thread_name,
        key=thread_id,
        use_container_width=True,
        type="primary" if is_active else "secondary",
    ):
        # Update the currently active conversation.
        st.session_state["thread_id"] = thread_id

        # Retrieve the selected conversation from LangGraph.
        messages = load_conversation(thread_id)

        # Convert LangChain message objects into dictionaries
        # that can be rendered by the Streamlit chat interface.
        temp_msg_dict = []

        for message in messages:
            # Identify messages sent by the user.
            if isinstance(message, HumanMessage):
                role = "user"

            # Identify messages generated by the AI.
            elif isinstance(message, AIMessage):
                role = "assistant"

            # Ignore system messages and other message types.
            else:
                continue

            temp_msg_dict.append({"role": role, "content": message.content})

        # Replace the current UI history with the selected
        # conversation's message history.
        st.session_state["messages_history"] = temp_msg_dict

        # Refresh the interface to update the active thread button.
        st.rerun()


# ==========================================================
#                   MAIN CHAT INTERFACE
# ==========================================================


# Render all previous messages of the active conversation.
for msg in st.session_state["messages_history"]:
    with st.chat_message(msg["role"]):
        st.markdown(msg["content"])


# Display the chat input field.
user_input = st.chat_input("Type here...")


# Process the message when the user submits an input.
if user_input:
    # Store the user's message in the frontend message history.
    st.session_state["messages_history"].append({"role": "user", "content": user_input})

    # Immediately display the user's message in the chat interface.
    with st.chat_message("user"):
        st.markdown(user_input)

    # Pass the active thread ID to LangGraph.
    # This allows the chatbot to resume the correct conversation
    # using its previously saved checkpoint.
    CONFIG = {"configurable": {"thread_id": st.session_state["thread_id"]}}

    # Generate and stream the AI response in real time.
    with st.chat_message("assistant"):
        ai_message = st.write_stream(
            message_chunk.content
            for message_chunk, metadata in chatbot.stream(
                {"messages": [HumanMessage(content=user_input)]},
                config=CONFIG,
                stream_mode="messages",
            )
            if isinstance(message_chunk, AIMessage)
            and isinstance(message_chunk.content, str)
        )

    # Store the complete AI response in the frontend history.
    st.session_state["messages_history"].append(
        {"role": "assistant", "content": ai_message}
    )
